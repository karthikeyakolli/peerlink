  /// Converts PDF to Word document (.docx) using OpenXML packaging.
  Future<File> convertPdfToWord(String inputPath, String outputPath) async {
    final file = File(inputPath);
    final text = file.existsSync() ? _safeReadText(file) : 'Word Document Content from PDF';

    final docXml = StringBuffer();
    docXml.write('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n');
    docXml.write('<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">\n<w:body>\n');

    final lines = text.split('\n');
    for (final line in lines) {
      final sanitized = line.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
      docXml.write('<w:p><w:r><w:t>$sanitized</w:t></w:r></w:p>\n');
    }
    docXml.write('</w:body>\n</w:document>');

    final contentTypesXml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n'
        '<Default Extension="xml" ContentType="application/xml"/>\n'
        '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>\n'
        '</Types>';

    final relsXml = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n'
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>\n'
        '</Relationships>';

    final files = {
      '[Content_Types].xml': utf8.encode(contentTypesXml),
      '_rels/.rels': utf8.encode(relsXml),
      'word/document.xml': utf8.encode(docXml.toString()),
    };

    final zipBytes = createZipArchive(files);
    final outFile = File(outputPath);
    _writeBytes(outputPath, zipBytes);
    return outFile;
  }

