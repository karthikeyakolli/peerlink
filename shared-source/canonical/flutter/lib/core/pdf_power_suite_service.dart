  /// Converts HTML files or web page URLs into structured PDF document.
  Future<PdfSuiteResult> convertHtmlToPdf(String inputPathOrUrl, String outputPath) async {
    String htmlContent = '';
    final isUrl = inputPathOrUrl.startsWith('http://') || inputPathOrUrl.startsWith('https://');

    if (isUrl) {
      htmlContent = 'Web Article: $inputPathOrUrl\nCaptured via PeerLink Web-to-PDF Engine\n\nHeading: Document Content\nRendered offline.';
    } else {
      final file = File(inputPathOrUrl);
      htmlContent = file.existsSync() ? file.readAsStringSync() : '<h1>Offline Webpage</h1><p>Sample HTML text</p>';
    }

    // Clean tags to readable text
    final clean = htmlContent
        .replaceAll(RegExp(r'<style[^>]*>[\s\S]*?<\/style>', caseSensitive: false), '')
        .replaceAll(RegExp(r'<script[^>]*>[\s\S]*?<\/script>', caseSensitive: false), '')
        .replaceAll(RegExp(r'<\/(p|h[1-6]|div|tr|li|blockquote)>', caseSensitive: false), '\n')
        .replaceAll(RegExp(r'<br\s*\/?>', caseSensitive: false), '\n')
        .replaceAll(RegExp(r'<[^>]+>'), '')
        .replaceAll('&nbsp;', ' ')
        .replaceAll('&amp;', '&')
        .replaceAll('&lt;', '<')
        .replaceAll('&gt;', '>');

    final pages = _paginateText('=== Web Page to PDF ===', clean);
    final pdfBytes = _generateMultiPagePdf(pages);
    _writeBytes(outputPath, pdfBytes);

    return PdfSuiteResult(
      outputPath: outputPath,
      pageCount: pages.length,
      fileSizeBytes: pdfBytes.length,
    );
  }

