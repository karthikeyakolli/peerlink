    final pages = <String>[];

    if (file.existsSync() && inputPath.toLowerCase().endsWith('.pptx')) {
      final preview = DocumentInspectorService.instance.extractOfficeTextSync(inputPath, 'pptx');
      final slides = preview.extractedText.split(RegExp(r'--- Slide \d+ ---'));
      for (int i = 0; i < slides.length; i++) {
        final content = slides[i].trim();
        if (content.isNotEmpty) {
          pages.add('=== Slide ${pages.length + 1} ===\n\n$content');
        }
      }
    }

    if (pages.isEmpty) {
      final raw = file.existsSync() ? _safeReadText(file) : 'Slide 1: Presentation Title\nSlide 2: Summary';
      pages.addAll(_paginateText('=== Presentation Slide ===', raw));
    }

    final pdfBytes = _generateMultiPagePdf(pages);
    _writeBytes(outputPath, pdfBytes);

    return PdfSuiteResult(
      outputPath: outputPath,
      pageCount: pages.length,
      fileSizeBytes: pdfBytes.length,
    );
  }

