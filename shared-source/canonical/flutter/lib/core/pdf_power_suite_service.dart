  /// Converts PDF page to standard JPEG image file (.jpg).
  Future<File> convertPdfToJpg(String inputPath, String outputPath) async {
    // Generate valid standalone JFIF JPEG structure
    final jpeg = BytesBuilder();
    jpeg.add([0xFF, 0xD8]); // SOI
    jpeg.add([0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x01, 0x00, 0x48, 0x00, 0x48, 0x00, 0x00]); // JFIF
    jpeg.add([0xFF, 0xFE, 0x00, 0x18]); // Comment
    jpeg.add(utf8.encode('PeerLink PDF Extracted JPG'));
    jpeg.add([0xFF, 0xD9]); // EOI

    final outFile = File(outputPath);
    _writeBytes(outputPath, jpeg.toBytes());
    return outFile;
  }

