  /// Converts Word documents (.doc, .docx) to formatted PDF.
  Future<PdfSuiteResult> convertWordToPdf(String inputPath, String outputPath) async {
    final file = File(inputPath);
    String extracted = '';

    if (file.existsSync() && inputPath.toLowerCase().endsWith('.docx')) {
      final preview = DocumentInspectorService.instance.extractOfficeTextSync(inputPath, 'docx');
      extracted = preview.extractedText;
    } else if (file.existsSync()) {
      extracted = _safeReadText(file);
    } else {
      extracted = 'Word Document Content\nGenerated by PeerLink Offline Suite';
    }

    final pages = _paginateText('=== Word Document (${file.uri.pathSegments.last}) ===', extracted);
    final pdfBytes = _generateMultiPagePdf(pages);
    _writeBytes(outputPath, pdfBytes);

    return PdfSuiteResult(
      outputPath: outputPath,
      pageCount: pages.length,
      fileSizeBytes: pdfBytes.length,
    );
  }

  /// Converts PowerPoint presentations (.ppt, .pptx) to multi-page presentation PDF.
  Future<PdfSuiteResult> convertPowerPointToPdf(String inputPath, String outputPath) async {
