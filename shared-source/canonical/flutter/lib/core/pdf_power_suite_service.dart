  List<String> _paginateText(String header, String fullText) {
    final lines = fullText.split('\n');
    final pages = <String>[];
    const int linesPerPage = 32;

    if (lines.isEmpty || fullText.trim().isEmpty) {
      return ['$header\n\n(No textual content)'];
    }

    for (int i = 0; i < lines.length; i += linesPerPage) {
      final slice = lines.skip(i).take(linesPerPage).join('\n');
      final pageNum = (i ~/ linesPerPage) + 1;
      pages.add('$header [Page $pageNum]\n\n$slice');
    }
    return pages;
  }

  void _writeBytes(String path, List<int> bytes) {
    final outFile = File(path);
    if (!outFile.parent.existsSync()) outFile.parent.createSync(recursive: true);
    outFile.writeAsBytesSync(bytes, flush: true);
  }

  String _safeReadText(File file) {
    try {
      return file.readAsStringSync();
    } catch (_) {
      return 'Document Content: ${file.uri.pathSegments.last}';
    }
  }

  /// Creates a standard PKZIP archive (uncompressed/stored mode) in pure Dart.
  static List<int> createZipArchive(Map<String, List<int>> files) {
    final buffer = BytesBuilder();
    final centralDir = BytesBuilder();
    int offset = 0;

    files.forEach((name, content) {
      final nameBytes = utf8.encode(name);
      final crc = _computeCrc32(content);
      final size = content.length;

      // Local Header: PK\x03\x04
      buffer.add([0x50, 0x4b, 0x03, 0x04]);
      buffer.add([0x14, 0x00]); // version needed 2.0
      buffer.add([0x00, 0x00]); // flags
      buffer.add([0x00, 0x00]); // method 0 (stored)
      buffer.add([0x00, 0x00, 0x00, 0x00]); // time & date
      buffer.add(_int32ToBytes(crc));
      buffer.add(_int32ToBytes(size)); // comp size
      buffer.add(_int32ToBytes(size)); // uncomp size
      buffer.add(_int16ToBytes(nameBytes.length));
      buffer.add([0x00, 0x00]); // extra len
      buffer.add(nameBytes);
      buffer.add(content);

      // Central Directory Record: PK\x01\x02
      centralDir.add([0x50, 0x4b, 0x01, 0x02]);
      centralDir.add([0x14, 0x00]); // version made by
      centralDir.add([0x14, 0x00]); // version needed
      centralDir.add([0x00, 0x00]); // flags
      centralDir.add([0x00, 0x00]); // method
      centralDir.add([0x00, 0x00, 0x00, 0x00]); // time & date
      centralDir.add(_int32ToBytes(crc));
      centralDir.add(_int32ToBytes(size));
      centralDir.add(_int32ToBytes(size));
      centralDir.add(_int16ToBytes(nameBytes.length));
      centralDir.add([0x00, 0x00]); // extra len
      centralDir.add([0x00, 0x00]); // comment len
      centralDir.add([0x00, 0x00]); // disk start
      centralDir.add([0x00, 0x00]); // internal attrs
      centralDir.add([0x00, 0x00, 0x00, 0x00]); // external attrs
      centralDir.add(_int32ToBytes(offset));
      centralDir.add(nameBytes);

      offset += 30 + nameBytes.length + size;
    });

    final centralDirBytes = centralDir.toBytes();
    final startOfCentralDir = buffer.length;
    buffer.add(centralDirBytes);

    // End of central directory record: PK\x05\x06
    buffer.add([0x50, 0x4b, 0x05, 0x06]);
    buffer.add([0x00, 0x00]); // disk number
    buffer.add([0x00, 0x00]); // disk with central dir
    buffer.add(_int16ToBytes(files.length)); // entries on this disk
    buffer.add(_int16ToBytes(files.length)); // total entries
    buffer.add(_int32ToBytes(centralDirBytes.length));
    buffer.add(_int32ToBytes(startOfCentralDir));
    buffer.add([0x00, 0x00]); // comment len

    return buffer.toBytes();
  }

  static int _computeCrc32(List<int> bytes) {
    int crc = 0xFFFFFFFF;
    for (final b in bytes) {
      crc ^= b;
      for (int i = 0; i < 8; i++) {
        if ((crc & 1) != 0) {
          crc = (crc >>> 1) ^ 0xEDB88320;
        } else {
          crc = crc >>> 1;
        }
      }
    }
    return crc ^ 0xFFFFFFFF;
  }

  static List<int> _int16ToBytes(int val) {
    return [val & 0xFF, (val >> 8) & 0xFF];
  }

  static List<int> _int32ToBytes(int val) {
    return [
      val & 0xFF,
      (val >> 8) & 0xFF,
      (val >> 16) & 0xFF,
      (val >> 24) & 0xFF,
    ];
  }

  /// Generates a valid PDF 1.4 document containing the given pages.
  static List<int> _generateMultiPagePdf(
    List<String> pages, {
    String? watermark,
    String? encryptionKey,
    int rotationDegrees = 0,
    bool includePageNumbers = false,
    bool isPdfA = false,
    bool isSearchableOcr = false,
  }) {
    final buffer = StringBuffer();
    final xref = <int>[];

    buffer.write('%PDF-1.4\n%\xE2\xE3\xCF\xD3\n');

    // 1: Catalog
    xref.add(buffer.length);
    if (isPdfA) {
      buffer.write('1 0 obj\n<< /Type /Catalog /Pages 2 0 R /OutputIntents [<< /Type /OutputIntent /S /GTS_PDFA1 /OutputConditionIdentifier (sRGB IEC61966-2.1) /Info (sRGB) >>] >>\nendobj\n');
    } else {
      buffer.write('1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n');
    }

    // 2: Pages
    xref.add(buffer.length);
    final kids = List.generate(pages.length, (i) => '${4 + i * 2} 0 R').join(' ');
    buffer.write('2 0 obj\n<< /Type /Pages /Kids [$kids] /Count ${pages.length} >>\nendobj\n');

    // 3: Font
    xref.add(buffer.length);
    buffer.write('3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n');

    for (int i = 0; i < pages.length; i++) {
      final pageObjNum = 4 + i * 2;
      final streamObjNum = pageObjNum + 1;

      // Page Object
      xref.add(buffer.length);
      buffer.write('$pageObjNum 0 obj\n');
      buffer.write('<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] ');
      if (rotationDegrees > 0) {
        buffer.write('/Rotate $rotationDegrees ');
      }
      buffer.write('/Contents $streamObjNum 0 R /Resources << /Font << /F1 3 0 R >> >> >>\nendobj\n');

      // Content Stream
      final textStream = StringBuffer();

      if (isSearchableOcr) {
        // Invisible searchable OCR text rendering mode (3 Tr)
        textStream.write('BT\n/F1 11 Tf\n3 Tr\n50 740 Td\n14 TL\n');
      } else {
        textStream.write('BT\n/F1 11 Tf\n50 740 Td\n14 TL\n');
      }

      final lines = pages[i].split('\n').take(45);
      for (final line in lines) {
        final sanitized = line.replaceAll(RegExp(r'[\\()]'), ' ');
        textStream.write('($sanitized) \'\n');
      }
      textStream.write('ET\n');

      // Watermark overlay if provided
      if (watermark != null && watermark.isNotEmpty) {
        final sanitizedWm = watermark.replaceAll(RegExp(r'[\\()]'), ' ');
        textStream.write('q\n');
        textStream.write('0.85 0.85 0.85 rg\n');
        textStream.write('BT\n/F1 38 Tf\n');
        textStream.write('0.707 0.707 -0.707 0.707 140 250 Tm\n');
        textStream.write('($sanitizedWm) Tj\n');
        textStream.write('ET\n');
        textStream.write('Q\n');
      }

      // Page numbers footer if requested
      if (includePageNumbers) {
        textStream.write('BT\n/F1 9 Tf\n270 30 Td\n');
        textStream.write('(Page ${i + 1} of ${pages.length}) Tj\nET\n');
      }

      final streamBytes = utf8.encode(textStream.toString());

      xref.add(buffer.length);
      buffer.write('$streamObjNum 0 obj\n<< /Length ${streamBytes.length} >>\nstream\n');
      buffer.write(textStream.toString());
      buffer.write('\nendstream\nendobj\n');
    }

    final startXref = buffer.length;
    buffer.write('xref\n0 ${xref.length + 1}\n');
    buffer.write('0000000000 65535 f \n');
    for (final offset in xref) {
      buffer.write('${offset.toString().padLeft(10, '0')} 00000 n \n');
    }

    buffer.write('trailer\n<< /Size ${xref.length + 1} /Root 1 0 R ');
    if (encryptionKey != null) {
      buffer.write('/Encrypt << /Filter /Standard /V 2 /R 3 /O ($encryptionKey) /U () /P -3904 >> ');
    }
    buffer.write('>>\n');
    buffer.write('startxref\n$startXref\n%%EOF\n');

    return utf8.encode(buffer.toString());
  }
