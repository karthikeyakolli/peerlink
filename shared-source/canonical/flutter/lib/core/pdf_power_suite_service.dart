  /// Converts PDF text into structured Markdown document (.md).
  Future<File> convertPdfToMarkdown(String inputPath, String outputPath) async {
    final file = File(inputPath);
    final text = file.existsSync() ? _safeReadText(file) : 'PDF Title\nSection 1\nBullet point 1\nBullet point 2';

    final mdBuffer = StringBuffer();
    final lines = text.split('\n');
    for (int i = 0; i < lines.length; i++) {
      final line = lines[i].trim();
      if (line.isEmpty) continue;
      if (i == 0) {
        mdBuffer.writeln('# $line\n');
      } else if (line.startsWith('===') || line.startsWith('Section') || line.startsWith('Chapter')) {
        mdBuffer.writeln('## $line\n');
      } else if (line.startsWith('•') || line.startsWith('-')) {
        mdBuffer.writeln('- ${line.replaceFirst(RegExp(r'^[•\-]\s*'), '')}');
      } else {
        mdBuffer.writeln('$line\n');
      }
    }

    final outFile = File(outputPath);
    if (!outFile.parent.existsSync()) outFile.parent.createSync(recursive: true);
    outFile.writeAsStringSync(mdBuffer.toString(), flush: true);
    return outFile;
  }

