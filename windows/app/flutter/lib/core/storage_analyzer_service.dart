/// Represents a redundant or storage-heavy file identified during deep clean analysis.
class StorageAnomalyItem {
  final String path;
  final String name;
  final int sizeBytes;
  final DateTime lastModified;
  final String extension;
  final String reason;

  const StorageAnomalyItem({
    required this.path,
    required this.name,
    required this.sizeBytes,
    required this.lastModified,
    required this.extension,
    required this.reason,
  });

  String get formattedSize {
    if (sizeBytes < 1024) return '$sizeBytes B';
    if (sizeBytes < 1024 * 1024) return '${(sizeBytes / 1024).toStringAsFixed(1)} KB';
    if (sizeBytes < 1024 * 1024 * 1024) return '${(sizeBytes / (1024 * 1024)).toStringAsFixed(1)} MB';
    return '${(sizeBytes / (1024 * 1024 * 1024)).toStringAsFixed(2)} GB';
  }
}

/// Represents a set of duplicate files sharing the same content.
class DuplicateFileGroup {
  final int sizeBytes;
  final String hash;
  final List<StorageAnomalyItem> files;

  const DuplicateFileGroup({
    required this.sizeBytes,
    required this.hash,
    required this.files,
  });

  int get reclaimableBytes => sizeBytes * (files.length - 1);

  String get formattedReclaimableSize {
    final b = reclaimableBytes;
    if (b < 1024) return '$b B';
    if (b < 1024 * 1024) return '${(b / 1024).toStringAsFixed(1)} KB';
    if (b < 1024 * 1024 * 1024) return '${(b / (1024 * 1024)).toStringAsFixed(1)} MB';
    return '${(b / (1024 * 1024 * 1024)).toStringAsFixed(2)} GB';
  }
}

/// Represents folder-level disk usage for the Visual Storage Analyzer.
class FolderSizeSummary {
  final String name;
  final String path;
  final int totalBytes;
  final int fileCount;

  const FolderSizeSummary({
    required this.name,
    required this.path,
    required this.totalBytes,
    required this.fileCount,
  });

  String get formattedSize {
    if (totalBytes < 1024) return '$totalBytes B';
    if (totalBytes < 1024 * 1024) return '${(totalBytes / 1024).toStringAsFixed(1)} KB';
    if (totalBytes < 1024 * 1024 * 1024) return '${(totalBytes / (1024 * 1024)).toStringAsFixed(1)} MB';
    return '${(totalBytes / (1024 * 1024 * 1024)).toStringAsFixed(2)} GB';
  }
}

/// Comprehensive report generated by the Visual Storage Analyzer & Deep Clean engine.
class StorageAnalysisReport {
  final List<StorageAnomalyItem> redundantApks;
  final List<StorageAnomalyItem> largeFiles;
  final List<DuplicateFileGroup> duplicateGroups;
  final List<StorageAnomalyItem> cacheFragments;
  final int totalReclaimableBytes;
  final int totalScannedBytes;
  final Map<ReceivedFileCategory, int> categoryBytes;
  final List<FolderSizeSummary> largestFolders;

  const StorageAnalysisReport({
    required this.redundantApks,
    required this.largeFiles,
    required this.duplicateGroups,
    required this.cacheFragments,
    required this.totalReclaimableBytes,
    this.totalScannedBytes = 0,
    this.categoryBytes = const {},
    this.largestFolders = const [],
  });

  String get formattedTotalScannedBytes {
    if (totalScannedBytes < 1024) return '$totalScannedBytes B';
    if (totalScannedBytes < 1024 * 1024) return '${(totalScannedBytes / 1024).toStringAsFixed(1)} KB';
    if (totalScannedBytes < 1024 * 1024 * 1024) return '${(totalScannedBytes / (1024 * 1024)).toStringAsFixed(1)} MB';
    return '${(totalScannedBytes / (1024 * 1024 * 1024)).toStringAsFixed(2)} GB';
  }

  String get formattedReclaimableBytes {
    if (totalReclaimableBytes < 1024) return '$totalReclaimableBytes B';
    if (totalReclaimableBytes < 1024 * 1024) {
      return '${(totalReclaimableBytes / 1024).toStringAsFixed(1)} KB';
    }
    if (totalReclaimableBytes < 1024 * 1024 * 1024) {
      return '${(totalReclaimableBytes / (1024 * 1024)).toStringAsFixed(1)} MB';
    }
    return '${(totalReclaimableBytes / (1024 * 1024 * 1024)).toStringAsFixed(2)} GB';
  }
}

/// Xiaomi MIUI / HyperOS-style Deep Clean analyzer for PeerLink.
/// Performs safe, user-confirmed hygiene scans for duplicate files, large files,
/// installer packages, and staging cache fragments.
class StorageAnalyzerService {
  static final StorageAnalyzerService _instance = StorageAnalyzerService._internal();
  static StorageAnalyzerService get instance => _instance;

  StorageAnalyzerService._internal();

  /// Default threshold for large file detection (50 MB).
  static const int defaultLargeFileThresholdBytes = 50 * 1024 * 1024;

  /// Scans the managed directory and generates an actionable storage analysis report.
  Future<StorageAnalysisReport> analyzeStorage({
    int largeFileThresholdBytes = defaultLargeFileThresholdBytes,
    Directory? customDirectory,
  }) async {
    final targetDir = customDirectory ?? ReceivedFilesService.instance.saveDirectory;
    final List<StorageAnomalyItem> redundantApks = [];
    final List<StorageAnomalyItem> largeFiles = [];
    final List<StorageAnomalyItem> cacheFragments = [];
    final Map<int, List<File>> sizeBuckets = {};
    final Map<ReceivedFileCategory, int> categoryBytes = {};
    final List<FolderSizeSummary> largestFolders = [];
    int totalScannedBytes = 0;

    const skipInternalDirs = {
      '.peerlink_trash',
      '.peerlink_safe_vault',
      'peerlink_staging',
      'peerlink_quarantine',
      '.git',
    };

    void scanFileEntity(File entity) {
      final stat = entity.statSync();
      final path = entity.path;
      final name = entity.uri.pathSegments.isNotEmpty
          ? entity.uri.pathSegments.last
          : path.split(RegExp(r'[\\/]')).last;
      final ext = name.contains('.') ? name.split('.').last.toLowerCase() : '';

      // 1. Check for Cache & Staging Junk
      if (name.endsWith('.part') ||
          name.endsWith('.tmp') ||
          name.endsWith('.corrupt') ||
          name.startsWith('.staging_')) {
        cacheFragments.add(StorageAnomalyItem(
          path: path,
          name: name,
          sizeBytes: stat.size,
          lastModified: stat.modified,
          extension: ext,
          reason: 'Unfinished or temporary transfer fragment',
        ));
        return; // Skip further classification for junk
      }

      totalScannedBytes += stat.size;
      final cat = ReceivedFilesService.instance.classifyExtension(ext);
      categoryBytes[cat] = (categoryBytes[cat] ?? 0) + stat.size;

      // 2. Check for Redundant APKs & Installers
      if (const {'apk', 'aab', 'exe', 'msi', 'dmg', 'pkg', 'deb', 'rpm'}.contains(ext)) {
        redundantApks.add(StorageAnomalyItem(
          path: path,
          name: name,
          sizeBytes: stat.size,
          lastModified: stat.modified,
          extension: ext,
          reason: 'Downloaded installer package',
        ));
      }

      // 3. Check for Large Files
      if (stat.size >= largeFileThresholdBytes) {
        largeFiles.add(StorageAnomalyItem(
          path: path,
          name: name,
          sizeBytes: stat.size,
          lastModified: stat.modified,
          extension: ext,
          reason: 'File exceeds ${largeFileThresholdBytes ~/ (1024 * 1024)} MB',
        ));
      }

      // Bucket by size for fast duplicate detection
      if (stat.size > 0) {
        sizeBuckets.putIfAbsent(stat.size, () => []).add(entity);
      }
    }

    ({int bytes, int files}) walkFolder(Directory dir, int depth) {
      int dirBytes = 0;
      int dirFiles = 0;
      if (depth > 4) return (bytes: 0, files: 0);
      try {
        for (final entity in dir.listSync(recursive: false, followLinks: false)) {
          final seg = entity.uri.pathSegments.where((s) => s.isNotEmpty).lastOrNull ?? '';
          if (skipInternalDirs.contains(seg)) continue;
          if (entity is File) {
            scanFileEntity(entity);
            dirBytes += entity.lengthSync();
            dirFiles++;
          } else if (entity is Directory) {
            final sub = walkFolder(entity, depth + 1);
            dirBytes += sub.bytes;
            dirFiles += sub.files;
          }
        }
      } catch (_) {}
      return (bytes: dirBytes, files: dirFiles);
    }

    if (targetDir.existsSync()) {
      try {
        final entities = targetDir.listSync(recursive: false, followLinks: false);
        for (final entity in entities) {
          final seg = entity.uri.pathSegments.where((s) => s.isNotEmpty).lastOrNull ?? '';
          if (skipInternalDirs.contains(seg)) continue;
          if (entity is File) {
            scanFileEntity(entity);
          } else if (entity is Directory) {
            final sub = walkFolder(entity, 1);
            if (sub.bytes > 0) {
              largestFolders.add(FolderSizeSummary(
                name: seg,
                path: entity.path,
                totalBytes: sub.bytes,
                fileCount: sub.files,
              ));
            }
          }
        }
      } catch (_) {}
    }

    largestFolders.sort((a, b) => b.totalBytes.compareTo(a.totalBytes));

    // 4. Compute Duplicate Files by checking SHA-256 for files sharing the exact same size
    final List<DuplicateFileGroup> duplicateGroups = [];
    for (final entry in sizeBuckets.entries) {
      if (entry.value.length < 2) continue;

      final Map<String, List<File>> hashBuckets = {};
      for (final file in entry.value) {
        final hash = await _calculateQuickHash(file);
        if (hash != null) {
          hashBuckets.putIfAbsent(hash, () => []).add(file);
        }
      }

      for (final hEntry in hashBuckets.entries) {
        if (hEntry.value.length > 1) {
          final items = hEntry.value.map((f) {
            final stat = f.statSync();
            final name = f.uri.pathSegments.isNotEmpty
                ? f.uri.pathSegments.last
                : f.path.split(RegExp(r'[\\/]')).last;
            final ext = name.contains('.') ? name.split('.').last.toLowerCase() : '';
            return StorageAnomalyItem(
              path: f.path,
              name: name,
              sizeBytes: stat.size,
              lastModified: stat.modified,
              extension: ext,
              reason: 'Exact duplicate content (SHA-256 matched)',
            );
          }).toList();

          duplicateGroups.add(DuplicateFileGroup(
            sizeBytes: entry.key,
            hash: hEntry.key,
            files: items,
          ));
        }
      }
    }

    // Sort large files descending
    largeFiles.sort((a, b) => b.sizeBytes.compareTo(a.sizeBytes));

    // Calculate total reclaimable bytes
    int totalReclaimable = 0;
    for (final item in cacheFragments) {
      totalReclaimable += item.sizeBytes;
    }
    for (final grp in duplicateGroups) {
      totalReclaimable += grp.reclaimableBytes;
    }
    for (final apk in redundantApks) {
      totalReclaimable += apk.sizeBytes;
    }

    return StorageAnalysisReport(
      redundantApks: redundantApks,
      largeFiles: largeFiles,
      duplicateGroups: duplicateGroups,
      cacheFragments: cacheFragments,
      totalReclaimableBytes: totalReclaimable,
      totalScannedBytes: totalScannedBytes,
      categoryBytes: categoryBytes,
      largestFolders: largestFolders.take(8).toList(),
    );
  }

  /// Calculates a SHA-256 hash using the first 64KB and last 64KB for speed, or full hash for small files.
  Future<String?> _calculateQuickHash(File file) async {
    try {
      final len = await file.length();
      if (len == 0) return null;

      final raf = await file.open(mode: FileMode.read);
      try {
        if (len <= 128 * 1024) {
          final bytes = await raf.read(len);
          return sha256.convert(bytes).toString();
        } else {
          final prefix = await raf.read(64 * 1024);
          await raf.setPosition(len - 64 * 1024);
          final suffix = await raf.read(64 * 1024);
          final combined = [...prefix, ...suffix];
          return sha256.convert(combined).toString();
        }
      } finally {
        await raf.close();
      }
    } catch (_) {
      return null;
    }
  }

  /// Purges all cache and temporary fragments safely.
  Future<int> purgeAllCacheFragments(List<StorageAnomalyItem> items) async {
    int count = 0;
    for (final item in items) {
      try {
        final f = File(item.path);
        if (f.existsSync()) {
          f.deleteSync();
          count++;
        }
      } catch (_) {}
    }
    return count;
  }

  /// Deletes specific files selected by the user.
  Future<int> deleteSelectedFiles(Iterable<String> paths) async {
    int count = 0;
    for (final p in paths) {
      try {
        final f = File(p);
        if (f.existsSync()) {
          f.deleteSync();
          count++;
        }
      } catch (_) {}
    }
    return count;
  }
}
